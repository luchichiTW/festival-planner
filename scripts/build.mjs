#!/usr/bin/env node
// Assembles one event from core/ and events/<slug>/. Copies and fills templates only — no transpiling, no packages.
//   node scripts/build.mjs <slug>                     → dist/<slug>/ (website, PWA) and dist-artifact/<slug>/index.html
//   node scripts/build.mjs <slug> --release-artifact  → also copies the single file to events/<slug>/artifact/index.html
//   node scripts/build.mjs site                       → dist-site/index.html, the chiparashi.tw/ homepage listing every event
// The build stops if scripts/validate.mjs finds an error.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { ROOT, loadEvent, listEvents, validate } from './validate.mjs';

const CORE = path.join(ROOT, 'core');
const STACKS = {
  display: '"PingFang TC", "Noto Sans TC", "Microsoft JhengHei", sans-serif',
  body: '"PingFang TC", "Noto Sans TC", "Microsoft JhengHei", system-ui, sans-serif',
  mono: 'ui-monospace, "SFMono-Regular", Menlo, Consolas, monospace',
};
const DOW = '日一二三四五六';

const read = (p) => fs.readFileSync(p, 'utf8');
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
// JSON that is safe inside a <script> element.
const inlineJSON = (v) => JSON.stringify(v).replace(/</g, '\\u003c').replace(/[\u2028\u2029]/g, (c) => (c === '\u2028' ? '\\u2028' : '\\u2029'));
const fill = (tpl, vars) => tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => {
  if (!(k in vars)) throw new Error(`template placeholder {{${k}}} has no value`);
  return vars[k];
});

// Build id: the git commit, so the service worker and 「關於」 show which version is running.
export function buildId() {
  if (process.env.FP_BUILD) return process.env.FP_BUILD;
  const git = (cmd) => execSync(cmd, { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  const stamp = Date.now().toString(36);
  try {
    const sha = git('git rev-parse --short=7 HEAD');
    return git('git status --porcelain') ? `${sha}-dev.${stamp}` : sha;
  } catch {
    return `dev.${stamp}`;
  }
}

function themeCSS(ev, fontSrc) {
  const vars = (tokens) => Object.entries(tokens).map(([k, v]) => `  --${k}: ${v};`).join('\n');
  const stageVars = (mode) => ev.stages.map((s) => `  --stage-${s.id}: ${s.color[mode]};`).join('\n');
  const faces = [];
  const fam = {};
  for (const role of ['display', 'body', 'mono']) {
    const f = ev.fonts?.[role];
    fam[role] = f?.family ? `"${f.family}", ${STACKS[role]}` : STACKS[role];
    if (f?.family && f.file) {
      faces.push(`@font-face { font-family: "${f.family}"; src: url(${fontSrc(f.file)}) format("woff2"); font-weight: ${f.weight || '400'}; font-display: swap; }`);
    }
  }
  return `/* Generated by scripts/build.mjs from events/${ev.slug}/event.json — edit that file, not this block. */
${faces.join('\n')}
:root {
  --display: ${fam.display};
  --body: ${fam.body};
  --mono: ${fam.mono};
${vars(ev.theme.dark)}
${stageVars('dark')}
  color-scheme: dark;
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
${vars(ev.theme.light).replace(/^/gm, '  ')}
${stageVars('light').replace(/^/gm, '  ')}
    color-scheme: light;
  }
}
:root[data-theme="light"] {
${vars(ev.theme.light)}
${stageVars('light')}
  color-scheme: light;
}
`;
}

// What the page needs at run time: event.json minus the build-only parts, plus the build id.
function clientConfig(ev, build, mode) {
  return {
    slug: ev.slug, name: ev.name, nameEn: ev.nameEn, shortName: ev.shortName, lang: ev.lang, timezone: ev.timezone,
    languages: ev.languages || ['zh'], wordmark: ev.wordmark,
    subtitle: ev.subtitle || '', subtitleEn: ev.subtitleEn, dataDate: ev.dataDate, sourceNote: ev.sourceNote, sourceNoteEn: ev.sourceNoteEn,
    days: ev.days, stages: ev.stages.map(({ id, name, short, en, shortEn, long }) => ({ id, name, short, en, shortEn, long })),
    features: ev.features || {}, lottery: ev.lottery, urls: ev.urls || {}, build, mode,
  };
}

function dayTabs(ev) {
  return ev.days.map((d, i) => {
    const [y, m, dd] = d.date.split('-').map(Number);
    const dow = DOW[new Date(Date.UTC(y, m - 1, dd)).getUTCDay()];
    return `        <button type="button" class="tab" id="day${i + 1}" aria-pressed="${i === 0}"><b>${esc(d.label)}</b><span class="tab-sub">${m}/${dd} ${dow}</span></button>`;
  }).join('\n');
}

export function build(slug, { releaseArtifact = false, out = path.join(ROOT, 'dist'), artifactOut = path.join(ROOT, 'dist-artifact') } = {}) {
  const loaded = loadEvent(slug);
  const report = validate(loaded);
  if (report.errors.length) {
    const e = new Error(`${slug}: 資料有 ${report.errors.length} 個錯誤，先跑 node scripts/validate.mjs ${slug}`);
    e.report = report;
    throw e;
  }
  const { event: ev, schedule, artists, venue, dir } = loaded;
  const build = buildId();
  const template = read(path.join(CORE, 'index.html'));
  const styles = read(path.join(CORE, 'styles.css'));
  const app = read(path.join(CORE, 'app.js'));
  const common = {
    lang: ev.lang, title: esc(ev.name), description: esc(ev.description || ev.name), build: esc(build),
    wordmark: esc(ev.wordmark?.text || ev.shortName), wordmarkSub: esc(ev.wordmark?.sub || ''), subtitle: esc(ev.subtitle || ''), dayTabs: dayTabs(ev),
  };
  // Venue images: on the website they're files next to the page (img/…); in the single file, data: URIs of the
  // Chinese versions only (the English ones would double the size).
  const venueFor = (src, keepEn) => venue && {
    ...venue,
    map: venue.map && { ...venue.map, image: src(venue.map.image), imageEn: keepEn && venue.map.imageEn ? src(venue.map.imageEn) : undefined },
    images: (venue.images || []).map((im) => ({ ...im, src: src(im.src), srcEn: keepEn && im.srcEn ? src(im.srcEn) : undefined })),
  };
  const dataJS = (mode, venueSrc) => `window.FP_EVENT = ${inlineJSON(clientConfig(ev, build, mode))};\nwindow.FP_DATA = ${inlineJSON({ schedule, artists })};\n`
    + (venue ? `window.FP_VENUE = ${inlineJSON(venueFor(venueSrc, mode !== 'artifact'))};\n` : '');
  const eventCSS = ev.css ? '\n/* ---------- event.css ---------- */\n' + read(path.join(dir, ev.css)) : '';
  const hasMap = !!(venue && venue.images && venue.images.length);
  const langBtn = (ev.languages || []).includes('en') ? '    <button type="button" class="hdr-btn hdr-lang" id="langBtn">EN</button>' : '';
  common.langBtn = langBtn;
  const mapBtn = hasMap ? '      <button type="button" class="dock-btn" id="mapBtn" aria-label="場地圖與官方時間表" data-i18n-attr="aria-label"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linejoin="round" aria-hidden="true"><path d="M9 4 3.5 6v14L9 18l6 2 5.5-2V4L15 6 9 4z"/><path d="M9 4v14M15 6v14"/></svg></button>' : '';
  common.mapBtn = mapBtn;

  /* ---------- website: dist/<slug>/ ---------- */
  const site = path.join(out, slug);
  fs.rmSync(site, { recursive: true, force: true });
  fs.mkdirSync(site, { recursive: true });
  const CORE_JS = ['i18n.js', 'app.js', 'embed.js', 'map.js', 'pwa.js'];
  const files = ['./', 'styles.css', 'data.js', ...CORE_JS, 'manifest.webmanifest'];
  const copy = (rel, name) => {
    fs.mkdirSync(path.dirname(path.join(site, name)), { recursive: true });
    fs.copyFileSync(path.join(dir, rel), path.join(site, name));
    files.push(name);
    return name;
  };
  const fontName = (rel) => `fonts/${path.basename(rel)}`;
  for (const role of ['display', 'body', 'mono']) if (ev.fonts?.[role]?.file) copy(ev.fonts[role].file, fontName(ev.fonts[role].file));
  const icon = {};
  if (ev.icons?.svg) icon.svg = copy(ev.icons.svg, 'icon.svg');
  for (const [size, rel] of Object.entries(ev.icons?.png || {})) icon[size] = copy(rel, `icon-${size}.png`);
  if (ev.icons?.maskable) icon.maskable = copy(ev.icons.maskable, 'icon-maskable-512.png');

  const themeColor = ev.icons?.themeColor || ev.theme.dark.bg;
  const head = [
    `<meta name="theme-color" content="${esc(themeColor)}">`,
    '<meta name="mobile-web-app-capable" content="yes">',
    '<meta name="apple-mobile-web-app-capable" content="yes">',
    // The page draws under the status bar (white text); the theme's --status-bar keeps it readable.
    '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">',
    `<meta name="apple-mobile-web-app-title" content="${esc(ev.shortName)}">`,
    '<link rel="manifest" href="manifest.webmanifest">',
    icon.svg && '<link rel="icon" href="icon.svg" type="image/svg+xml">',
    !icon.svg && icon['192'] && '<link rel="icon" href="icon-192.png" sizes="192x192" type="image/png">',
    icon['180'] && '<link rel="apple-touch-icon" href="icon-180.png">',
    ev.fonts?.display?.file && `<link rel="preload" href="${fontName(ev.fonts.display.file)}" as="font" type="font/woff2" crossorigin>`,
    '<link rel="stylesheet" href="styles.css">',
  ].filter(Boolean).join('\n');
  // Venue images ship with the site and go into the offline cache.
  const imgName = (rel) => `img/${path.basename(rel)}`;
  if (venue) {
    const rels = new Set([venue.map?.image, venue.map?.imageEn, ...(venue.images || []).flatMap((im) => [im.src, im.srcEn])].filter(Boolean));
    for (const rel of rels) copy(rel, imgName(rel));
  }
  const scripts = ['data.js', ...CORE_JS].map((f) => `<script src="${f}"></script>`).join('\n');
  fs.writeFileSync(path.join(site, 'index.html'), fill(template, { ...common, head, scripts }).replace(/ *<!-- \/?fp:(web|body) -->\n/g, ''));
  fs.writeFileSync(path.join(site, 'styles.css'), themeCSS(ev, fontName) + '\n' + styles + eventCSS);
  fs.writeFileSync(path.join(site, 'data.js'), dataJS('web', imgName));
  fs.writeFileSync(path.join(site, 'app.js'), app);
  for (const f of CORE_JS) if (f !== 'app.js') fs.copyFileSync(path.join(CORE, f), path.join(site, f));
  fs.writeFileSync(path.join(site, 'manifest.webmanifest'), JSON.stringify({
    name: ev.name, short_name: ev.shortName, description: ev.description || ev.name, lang: ev.lang,
    id: './', start_url: './', scope: './', display: 'standalone',
    background_color: themeColor, theme_color: themeColor,
    icons: [
      icon.svg && { src: 'icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
      icon['192'] && { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      icon['512'] && { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      icon.maskable && { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ].filter(Boolean),
  }, null, 2) + '\n');
  fs.writeFileSync(path.join(site, 'sw.js'), read(path.join(CORE, 'sw.template.js'))
    .replace("'__VERSION__'", JSON.stringify(build))
    .replace("'__CACHE__'", JSON.stringify(`fp-${slug}-${build}`))
    .replace("'__PREFIX__'", JSON.stringify(`fp-${slug}-`))
    .replace('__FILES__', JSON.stringify(files)));

  // /<slug> → /<slug>/ for every event built into this folder (relative links and the service worker scope need the slash).
  const built = fs.readdirSync(out, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(out, d.name, 'sw.js'))).map((d) => d.name).sort();
  fs.writeFileSync(path.join(out, '_redirects'), built.map((s) => `/${s} /${s}/ 301`).join('\n') + '\n');

  /* ---------- single-file artifact ---------- */
  const dataURI = (rel) => `data:font/woff2;base64,${fs.readFileSync(path.join(dir, rel)).toString('base64')}`;
  const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };
  const imgURIs = new Map();
  const imgURI = (rel) => {
    if (!imgURIs.has(rel)) imgURIs.set(rel, `data:${MIME[path.extname(rel).toLowerCase()] || 'application/octet-stream'};base64,${fs.readFileSync(path.join(dir, rel)).toString('base64')}`);
    return imgURIs.get(rel);
  };
  const body = /<!-- fp:body -->\n([\s\S]*?)<!-- \/fp:body -->/.exec(fill(template, { ...common, head: '', scripts: '' }))[1]
    .replace(/ *<!-- fp:web -->[\s\S]*?<!-- \/fp:web -->\n/g, '');
  const single = [
    `<title>${esc(ev.name)}</title>`,
    '<meta name="claude:viewport-fit-sides" content="cover">',
    `<style>\n${themeCSS(ev, dataURI)}\n${styles}${eventCSS}</style>`,
    body.trimEnd(),
    `<script>\n${dataJS('artifact', imgURI)}</script>`,
    `<script>\n${read(path.join(CORE, 'i18n.js'))}</script>`,
    `<script>\n${app}</script>`,
    hasMap ? `<script>\n${read(path.join(CORE, 'map.js'))}</script>` : '',
    `<script>\n${read(path.join(CORE, 'cloud.js'))}</script>`,
  ].join('\n') + '\n';
  const artDir = path.join(artifactOut, slug);
  fs.mkdirSync(artDir, { recursive: true });
  fs.writeFileSync(path.join(artDir, 'index.html'), single);
  if (releaseArtifact) fs.writeFileSync(path.join(dir, 'artifact', 'index.html'), single);

  return { build, site, artifact: path.join(artDir, 'index.html'), files, report };
}

/* ---------- homepage: one self-contained page listing every event under events/ ---------- */
export function buildSite({ out = path.join(ROOT, 'dist-site') } = {}) {
  const events = listEvents().map((slug) => {
    const loaded = loadEvent(slug);
    const report = validate(loaded);
    if (report.errors.length) throw Object.assign(new Error(`${slug} 的資料有錯，首頁不建置`), { report });
    return loaded.event;
  }).sort((a, b) => b.days[0].date.localeCompare(a.days[0].date)); // the page re-sorts by today's date
  const icon = (ev) => (ev.icons?.png?.['192'] ? 'icon-192.png' : ev.icons?.svg ? 'icon.svg' : null);
  const cards = events.map((ev) => {
    const img = icon(ev);
    return `      <li><a class="ev" href="${ev.slug}/" style="--cd:${esc(ev.theme.dark['accent-text'] || ev.theme.dark.gold)};--cl:${esc(ev.theme.light['accent-text'] || ev.theme.light.gold)}">`
      + (img ? `<img class="ev-icon" src="${ev.slug}/${img}" alt="" width="60" height="60">` : '<span class="ev-icon"></span>')
      + `<span class="ev-body"><b class="ev-name">${esc(ev.name)}</b><span class="ev-sub">${esc(ev.subtitle || '')}</span><span class="ev-status"></span></span></a></li>`;
  }).join('\n');
  const repo = events.find((ev) => ev.urls?.repo)?.urls.repo || 'https://github.com/luchichiTW/festival-planner';
  const html = fill(read(path.join(ROOT, 'site', 'index.html')), {
    description: esc(`音樂祭排團工具：${events.map((ev) => ev.name).join('、')}。看時間表、排出自己的團序、撞團抽籤，離線也能用。非官方工具。`),
    cards,
    repo: esc(repo),
    repoLabel: esc(repo.replace(/^https:\/\//, '')),
    events: inlineJSON(events.map((ev) => ({ slug: ev.slug, tz: ev.timezone, days: ev.days.map((d) => ({ date: d.date, label: d.label })) }))),
  });
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'index.html'), html);
  return { out, events: events.map((ev) => ev.slug) };
}

function main() {
  const args = process.argv.slice(2);
  const slug = args.find((a) => !a.startsWith('--'));
  if (!slug) {
    console.error('用法：node scripts/build.mjs <活動代號> [--release-artifact]，或 node scripts/build.mjs site（首頁）');
    process.exit(2);
  }
  if (slug === 'site') {
    try {
      const r = buildSite();
      console.log(`✓ 首頁 → ${path.relative(ROOT, r.out)}/index.html（${r.events.join('、')}）`);
    } catch (e) {
      console.error(`✗ ${e.message}`);
      (e.report?.errors || []).forEach((m) => console.error(`  ✗ ${m}`));
      process.exit(1);
    }
    return;
  }
  try {
    const r = build(slug, { releaseArtifact: args.includes('--release-artifact') });
    console.log(`✓ ${slug} @ ${r.build}`);
    console.log(`  網站     ${path.relative(ROOT, r.site)}/（${r.files.length} 個檔案進離線快取）`);
    console.log(`  artifact ${path.relative(ROOT, r.artifact)}${args.includes('--release-artifact') ? `，並更新 events/${slug}/artifact/index.html` : ''}`);
    r.report.warnings.forEach((m) => console.log(`  ! ${m}`));
  } catch (e) {
    console.error(`✗ ${e.message}`);
    (e.report?.errors || []).forEach((m) => console.error(`  ✗ ${m}`));
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
